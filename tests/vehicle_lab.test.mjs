import assert from "node:assert/strict";
import {createVehicleState,stepVehicle,toleranceBounds,toleranceSamples,quarterStep} from "../site/model.js";
import {readFileSync} from "node:fs";
let s=createVehicleState();
for(let i=0;i<300;i++)s=stepVehicle(s,{},0.01);
assert.equal(s.speed,0);
assert.equal(s.distance,0);
let driven=createVehicleState();
for(let i=0;i<800;i++)driven=stepVehicle(driven,{throttle:0.7},0.01);
assert(driven.speed>5&&driven.speed<80);
assert(driven.fuelKg>0);
const before=driven.speed;
for(let i=0;i<400;i++)driven=stepVehicle(driven,{brake:0.8},0.01);
assert(driven.speed<before&&driven.speed>=0);
let flat=createVehicleState(),uphill=createVehicleState();
for(let i=0;i<1000;i++){flat=stepVehicle(flat,{throttle:0.3},0.01);uphill=stepVehicle(uphill,{throttle:0.3,grade:7},0.01);}
assert(uphill.distance<flat.distance);
let rough=createVehicleState();rough.speed=15;
for(let i=0;i<300;i++)rough=stepVehicle(rough,{roughness:0.04},0.01);
assert(Math.abs(rough.front.zu)>1e-8);
assert(Number.isFinite(rough.rear.zs));
const k={ms:300,mu:40,ks:16000,cs:0,kt:200000,ct:0};
const energy=x=>0.5*k.ms*x.vs**2+0.5*k.mu*x.vu**2+0.5*k.ks*(x.zs-x.zu)**2+0.5*k.kt*x.zu**2;
let c={zs:0.015,vs:0,zu:0,vu:0};const initial=energy(c);
for(let i=0;i<10000;i++)c=quarterStep(c,k,0,0,0.0005);
assert(Math.abs(energy(c)/initial-1)<0.001);
const b=toleranceBounds({});
assert(Math.abs(b.minimumMm-0.03)<1e-9);
assert(Math.abs(b.maximumMm-0.17)<1e-9);
assert(toleranceBounds({scale:2}).minimumMm<b.minimumMm);
const m=toleranceSamples({},1500,99);
assert.equal(m.samples.length,1500);
assert.deepEqual(m.samples,toleranceSamples({},1500,99).samples);
assert(m.passRate>=0&&m.passRate<=1);
assert.throws(()=>stepVehicle(createVehicleState(),{},0.1),RangeError);
assert(readFileSync("site/index.html","utf8").includes('type="module"'));
console.log("PASS vehicle dynamics, grade, energy, tolerance, and sampling");
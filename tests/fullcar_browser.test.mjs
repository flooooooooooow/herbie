import assert from "node:assert/strict";
import {createRideState,rideStep,rideEnergy,cornerDynamics,rideVector,roadAt,sampleRoad,createFullCarState,fullCarStep,defaultRideParameters} from "../site/fullcar.js";
import {createVehicleState,stepVehicle} from "../site/model.js";
const flat=Array.from({length:4},()=>({heightM:0,velocityMps:0}));
let parked=createRideState();
for(let i=0;i<2000;i++)parked=rideStep(parked,flat,flat,flat,0,0,0.001);
assert(Math.abs(parked.heaveM)<1e-13);
assert(parked.wheelM.every(q=>q===0));
const initial=createRideState();initial.heaveM=0.025;initial.wheelM[0]=0.02;
const conservative={...defaultRideParameters,damperNsPerM:[0,0,0,0],tireDamperNsPerM:[0,0,0,0]};
let oscillating=structuredClone(initial);const e0=rideEnergy(oscillating,conservative);
for(let i=0;i<4000;i++)oscillating=rideStep(oscillating,flat,flat,flat,0,0,0.001,conservative);
assert(Math.abs(rideEnergy(oscillating,conservative)/e0-1)<0.001,"undamped energy conservation");
let damped=structuredClone(initial);
for(let i=0;i<4000;i++)damped=rideStep(damped,flat,flat,flat,0,0,0.001);
assert(rideEnergy(damped)<rideEnergy(initial)*0.02,"dissipative damping");
const bump=[{heightM:0.03,velocityMps:0},...flat.slice(1)];
let excited=createRideState();
for(let i=0;i<400;i++)excited=rideStep(excited,bump,bump,bump,0,0,0.001);
assert(Math.abs(excited.rollRad)>1e-6,"independent left wheel excites roll");
assert(Math.abs(excited.pitchRad)>1e-6,"front wheel excites pitch");
assert(Math.abs(excited.wheelM[0])>1e-6,"front-left wheel responds");
const ride=createRideState();
const loads=cornerDynamics(rideVector(ride),flat,defaultRideParameters,{});
assert(loads.normalLoadN.every(x=>x>0),"static contact normal");
assert.equal(roadAt(10,1,0),0);
assert.notEqual(roadAt(19,1,0.04),roadAt(19,-1,0.04));
const replayA=sampleRoad(20,11,0.04,0.01);
assert.deepEqual(replayA,sampleRoad(20,11,0.04,0.01));
assert.throws(()=>rideStep(ride,flat,flat,flat,0,0,-1),RangeError);
let full=createFullCarState(createVehicleState());
for(let i=0;i<1000;i++)full=fullCarStep(full,{throttle:0.45,roughness:0.035,steer:0.015},0.01,stepVehicle);
assert(full.base.speed>0);
assert(full.ride.wheelM.every(Number.isFinite));
assert(full.wheelLoadsN.every(x=>x>=0));
assert.equal(full.time,full.base.time);
console.log("PASS: seven-DOF full car, roll/pitch asymmetry, conservative/damped dynamics, contacts and reproducible road");
